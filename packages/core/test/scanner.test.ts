import { describe, it, expect, beforeAll } from 'vitest';
import { mkdtempSync, mkdirSync, writeFileSync, symlinkSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { scanWorkspace } from '../src/scanner/scan.js';

let root: string;
const put = (rel: string, content = 'export const x = 1;\n') => {
  const abs = join(root, rel); mkdirSync(dirname(abs), { recursive: true }); writeFileSync(abs, content);
};

beforeAll(() => {
  root = mkdtempSync(join(tmpdir(), 'scan-'));
  put('src/a.ts'); put('src/b.tsx'); put('src/z.ts');
  put('src/types.d.ts', 'export type T = 1;');
  put('node_modules/x/i.ts'); put('dist/o.ts'); put('build/o.ts'); put('.next/o.ts');
  put('config/secrets/key.ts'); put('secrets/k.ts'); put('prod.env'); put('keys/cert.pem');
  put('src/big.ts', 'export const s = "' + 'x'.repeat(3000) + '";');
  put('src/gen.ts', '// @generated by tool\nexport const g = 1;\n');
  put('src/lib.min.ts');
  put('src/bin.ts', 'abc\u0000def');
  put('.gitignore', 'ignored/\n*.local.ts\n');
  put('ignored/i.ts'); put('src/own.local.ts');
  put('pkg/.gitignore', 'private.ts\n'); put('pkg/private.ts'); put('pkg/public.ts'); put('other/private.ts');
  put('tsconfig.json', '{}'); put('pkg/tsconfig.json', '{}'); put('node_modules/x/tsconfig.json', '{}');
  put('readme.md', '# x'); put('src/script.js', 'x');
  try { symlinkSync(join(root, 'src'), join(root, 'linked')); } catch { /* beberapa OS butuh hak khusus */ }
});

describe('scanWorkspace (FR-SCN-01..05)', () => {
  it('hanya .ts dan .tsx yang lolos aturan, urut menurut path', () => {
    const r = scanWorkspace(root, { maxFileSizeKb: 2 });
    expect(r.files.map((f) => f.path)).toEqual([
      'other/private.ts', 'pkg/public.ts', 'src/a.ts', 'src/b.tsx', 'src/z.ts',
    ]);
  });
  it('menghormati .gitignore akar dan .gitignore bersarang (hanya cakupannya)', () => {
    const paths = scanWorkspace(root, { maxFileSizeKb: 2 }).files.map((f) => f.path);
    expect(paths).not.toContain('ignored/i.ts');
    expect(paths).not.toContain('src/own.local.ts');
    expect(paths).not.toContain('pkg/private.ts');
    expect(paths).toContain('other/private.ts');
  });
  it('respectGitignore=false mengabaikan .gitignore tetapi tetap memakai pola exclude', () => {
    const paths = scanWorkspace(root, { maxFileSizeKb: 2, respectGitignore: false }).files.map((f) => f.path);
    expect(paths).toContain('ignored/i.ts');
    expect(paths).toContain('pkg/private.ts');
    expect(paths).not.toContain('node_modules/x/i.ts');
  });
  it('pola **/secrets/** dan *.env tidak pernah lolos', () => {
    const paths = scanWorkspace(root, { maxFileSizeKb: 2 }).files.map((f) => f.path);
    expect(paths.some((p) => p.includes('secrets'))).toBe(false);
  });
  it('mencatat alasan pengecualian', () => {
    const s = scanWorkspace(root, { maxFileSizeKb: 2 }).skipped;
    expect(s).toMatchObject({ declaration: 1, tooLarge: 1, binary: 1 });
    expect(s.generated).toBe(2); // gen.ts dan lib.min.ts
  });
  it('.d.ts masuk bila diaktifkan', () => {
    expect(scanWorkspace(root, { maxFileSizeKb: 2, includeDeclarationFiles: true }).files.map((f) => f.path)).toContain('src/types.d.ts');
  });
  it('menemukan tsconfig di luar direktori terkecualikan', () => {
    expect(scanWorkspace(root).tsconfigs).toEqual(['pkg/tsconfig.json', 'tsconfig.json']);
  });
  it('tidak mengikuti symlink (tidak ada entri ganda)', () => {
    expect(scanWorkspace(root, { maxFileSizeKb: 2 }).files.some((f) => f.path.startsWith('linked/'))).toBe(false);
  });
  it('deterministik: dua kali pindai menghasilkan daftar identik', () => {
    expect(scanWorkspace(root)).toEqual(scanWorkspace(root));
  });
});
